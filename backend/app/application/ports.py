from __future__ import annotations

from typing import Protocol
from datetime import datetime

from app.domain.reports import Report
from app.application.llm import LLMRequest, LLMResult, ModelTrace
from app.domain.approvals import Approval


class ReportStore(Protocol):
    async def save(self, report: Report) -> None: ...

    async def get(self, report_id: str) -> Report | None: ...

    async def list(self, limit: int, offset: int) -> tuple[list[Report], int]: ...

    async def update_priority(self, report: Report) -> None: ...

    async def update_classification(self, report: Report, trace: ModelTrace) -> None: ...

    async def update_checks(self, report: Report, traces: list[ModelTrace]) -> None: ...

    async def update_briefings(self, report: Report, trace: ModelTrace | None = None) -> None: ...

    async def recover_pipeline(self) -> list[str]: ...

    async def claim_pipeline(self, report_id: str) -> bool: ...

    async def fail_pipeline(self, report_id: str, code: str) -> None: ...


class LLMGateway(Protocol):
    async def generate(self, request: LLMRequest) -> LLMResult: ...

    async def aclose(self) -> None: ...


class HumanApprovalStore(Protocol):
    """Approval capability is separate from the pipeline's ReportStore contract."""

    async def approve_briefing(self, report_id: str, briefing_id: str, director: str,
                              acknowledge_review: bool, approved_at: datetime) -> Approval: ...
